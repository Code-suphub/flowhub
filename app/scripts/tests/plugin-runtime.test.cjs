test('floating workspace handles native selection, overflow, refresh, collapse and stale responses',async()=>{
 h.environment();global.ResizeObserver=class{observe(){}disconnect(){}};
 let plugins=Array.from({length:5},(_,i)=>({enabled:true,manifest:{id:`p${i}`,name:`Plugin ${i}`,ui:'ui/index.html'}}));
 let state={module:'extensions',open:false,revision:0};const calls=[];
 window.__TAURI__.core.invoke=async(command,args)=>{
  if(command==='plugin_api')return plugins;
  calls.push(args);
  if(args.action==='select')state={module:args.module,open:true,revision:state.revision+1};
  if(args.action==='close'||args.action==='hide')state={...state,open:false,revision:state.revision+1};
  return state;
 };
 vm.runInNewContext(source,{window,console});await window.FlowHubPluginIntegration.refresh();
 const {PluginWorkspace}=require('../../src/plugin-workspace/index.tsx');
 const dock=await h.mount(PluginWorkspace,{view:'dock'});
 assert.equal(dock.container.querySelectorAll('.settings-dock-plugin').length,3);
 await h.click(dock.container.querySelector('[aria-label="更多插件（2）"]'));
 assert.equal(calls.at(-1).module,'overflow');assert.equal(document.querySelector('[role=menu]'),null);
 const panel=await h.mount(PluginWorkspace,{view:'panel'});
 await h.click(h.button(panel.container,'Plugin 4'));
 const frame=panel.container.querySelector('iframe');assert.match(frame.src,/p4/);assert.equal(frame.getAttribute('sandbox'),'allow-scripts');
 await h.act(async()=>window.dispatchEvent(new window.CustomEvent('flowhub-workspace',{detail:{module:'plugin:p1',open:true,revision:99}})));
 assert.equal(panel.container.querySelector('iframe'),frame);assert.match(frame.src,/p1/);
 await h.act(async()=>window.dispatchEvent(new window.CustomEvent('flowhub-workspace',{detail:{module:'extensions',open:false,revision:2}})));
 assert.equal(panel.container.querySelector('iframe'),frame,'old ready/command responses cannot overwrite newer native state');
 state={module:'plugin:p1',open:true,revision:99};
 plugins=plugins.map(p=>({...p,enabled:p.manifest.id!=='p1'}));
 await h.act(async()=>window.FlowHubPluginIntegration.refresh());
 assert.equal(panel.container.querySelector('h1').textContent,'插件市场','disabling the active plugin falls back to market');
 await h.key(panel.container.querySelector('[aria-label="收起插件面板"]'),'Escape');
 assert.equal(panel.container.querySelector('iframe'),null,'collapsing releases the iframe and its RPC binding');
 await h.click(dock.container.querySelector('[aria-label="隐藏插件栏"]'));assert.equal(calls.at(-1).action,'hide');
 await panel.unmount();await dock.unmount();delete window.FlowHubPluginIntegration;delete global.ResizeObserver;
});
